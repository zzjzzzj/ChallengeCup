"""Run the final eight full-image detection experiments.

This is the maintained experiment matrix. It compares YOLOv8n and a
Faster R-CNN ResNet18-FPN detector across original/augmented training data
and pretrained/random initialization. All groups use the same validation
and independent test manifests generated by
``detector_module.prepare_comparison_dataset``.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parent
DEFAULT_DATA_DIR = ROOT / "detector_module" / "artifacts" / "comparison_dataset"
DEFAULT_RUNS_DIR = ROOT / "detector_module" / "runs"


@dataclass(frozen=True)
class Experiment:
    name: str
    model: str
    command: tuple[str, ...]
    done_marker: Path


def build_experiments(
    data_dir: Path,
    runs_dir: Path,
    yolo_epochs: int = 150,
    resnet_noaug_epochs: int = 40,
    resnet_aug_epochs: int = 6,
) -> list[Experiment]:
    experiments: list[Experiment] = []
    for data_tag, yaml_name in (("noaug", "data_noaug.yaml"), ("aug", "data_aug.yaml")):
        data_path = data_dir / yaml_name
        for init_tag, scratch_flag in (
            ("pretrained", ()),
            ("scratch", ("--no-pretrained",)),
        ):
            yolo_name = f"cmp8_yolov8n_{data_tag}_{init_tag}"
            experiments.append(
                Experiment(
                    name=yolo_name,
                    model="yolo",
                    command=(
                        sys.executable,
                        "-u",
                        "-m",
                        "detector_module.train_detector_ablation",
                        "--data",
                        str(data_path),
                        "--project",
                        str(runs_dir),
                        "--name",
                        yolo_name,
                        "--epochs",
                        str(yolo_epochs),
                        "--batch-size",
                        "16",
                        "--workers",
                        "4",
                        "--eval-split",
                        "test",
                        "--seed",
                        "42",
                        "--exist-ok",
                        *scratch_flag,
                    ),
                    done_marker=runs_dir / yolo_name / "ablation_summary.json",
                )
            )

            resnet_name = f"cmp8_resnet18det_{data_tag}_{init_tag}"
            resnet_epochs = resnet_noaug_epochs if data_tag == "noaug" else resnet_aug_epochs
            experiments.append(
                Experiment(
                    name=resnet_name,
                    model="resnet",
                    command=(
                        sys.executable,
                        "-u",
                        "-m",
                        "detector_module.resnet18_detector",
                        "--data",
                        str(data_path),
                        "--output",
                        str(runs_dir / resnet_name),
                        "--epochs",
                        str(resnet_epochs),
                        "--patience",
                        "10",
                        "--batch-size",
                        "4",
                        "--workers",
                        "0",
                        "--seed",
                        "42",
                        *scratch_flag,
                    ),
                    done_marker=runs_dir / resnet_name / "metrics.json",
                )
            )
    return experiments


def main() -> None:
    parser = argparse.ArgumentParser(description="运行最终八组端到端检测实验")
    parser.add_argument("--data-dir", type=Path, default=DEFAULT_DATA_DIR)
    parser.add_argument("--runs-dir", type=Path, default=DEFAULT_RUNS_DIR)
    parser.add_argument("--model", choices=("all", "yolo", "resnet"), default="all")
    parser.add_argument("--only", nargs="*", help="只运行指定实验名")
    parser.add_argument("--yolo-epochs", type=int, default=150)
    parser.add_argument("--resnet-noaug-epochs", type=int, default=40)
    parser.add_argument("--resnet-aug-epochs", type=int, default=6)
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--dry-run", action="store_true", help="只打印命令，不启动训练")
    args = parser.parse_args()

    data_dir = args.data_dir.resolve()
    runs_dir = args.runs_dir.resolve()
    for yaml_name in ("data_noaug.yaml", "data_aug.yaml"):
        if not (data_dir / yaml_name).is_file():
            raise FileNotFoundError(
                f"缺少 {data_dir / yaml_name}。请先运行 prepare-comparison。"
            )
    experiments = build_experiments(
        data_dir,
        runs_dir,
        yolo_epochs=args.yolo_epochs,
        resnet_noaug_epochs=args.resnet_noaug_epochs,
        resnet_aug_epochs=args.resnet_aug_epochs,
    )
    if args.model != "all":
        experiments = [experiment for experiment in experiments if experiment.model == args.model]
    if args.only:
        requested = set(args.only)
        experiments = [experiment for experiment in experiments if experiment.name in requested]
        unknown = requested - {experiment.name for experiment in experiments}
        if unknown:
            raise ValueError(f"未知或被 --model 排除的实验名: {sorted(unknown)}")
    if not experiments:
        raise ValueError("没有可运行的实验")

    runs_dir.mkdir(parents=True, exist_ok=True)
    log_dir = runs_dir / "logs"
    log_dir.mkdir(exist_ok=True)
    records: list[dict] = []
    for index, experiment in enumerate(experiments, start=1):
        prefix = f"[{index}/{len(experiments)}] {experiment.name}"
        if args.dry_run:
            print(prefix)
            print(subprocess.list2cmdline(experiment.command))
            records.append({"name": experiment.name, "status": "dry-run"})
            continue
        if experiment.done_marker.is_file() and not args.force:
            print(f"{prefix} 已完成，跳过", flush=True)
            records.append({"name": experiment.name, "status": "skipped"})
            continue
        log_path = log_dir / f"{experiment.name}.log"
        print(f"{prefix} 开始", flush=True)
        started_at = time.perf_counter()
        with log_path.open("w", encoding="utf-8", errors="replace") as log:
            completed = subprocess.run(
                experiment.command,
                cwd=ROOT,
                stdout=log,
                stderr=subprocess.STDOUT,
                text=True,
            )
        minutes = round((time.perf_counter() - started_at) / 60, 2)
        record = {
            "name": experiment.name,
            "status": "completed" if completed.returncode == 0 else "failed",
            "returncode": completed.returncode,
            "minutes": minutes,
            "log": str(log_path),
        }
        records.append(record)
        print(f"{prefix} {record['status']}，{minutes} 分钟", flush=True)
        if completed.returncode:
            break

    (runs_dir / "matrix_log.json").write_text(
        json.dumps({"runs": records}, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    failures = [record for record in records if record.get("status") == "failed"]
    if failures:
        raise SystemExit(f"实验失败，日志: {failures[0]['log']}")


if __name__ == "__main__":
    main()
